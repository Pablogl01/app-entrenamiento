export function seedExercises(userId: string): Exercise[] {
  return ROWS.map(([name, muscle_group, load_type, min_increment, mode]) => ({
    id: crypto.randomUUID(),
    user_id: userId,
    name,
    muscle_group,
    load_type,
    min_increment,
    unit_mode: mode ?? 'weight_reps',
    notes: '',
    is_custom: false,
    archived: false,
    image: SEED_IMAGES[name] ?? null,
  }))
}
